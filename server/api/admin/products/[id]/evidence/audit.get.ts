import { createError, getRouterParam } from 'h3'
import { adminFetch, assertProductExists } from '~/server/utils/adminDirectusClient'
import {
  computeEvidenceAuditEntries,
  type EvidenceAuditEntry,
  type EvidenceRevision,
  type EvidenceSourceRecordRef,
} from '~/server/utils/productEvidenceLinks'

export type { EvidenceAuditAction, EvidenceAuditEntry } from '~/server/utils/productEvidenceLinks'

/**
 * Read-only audit trail for this product's Specifications evidence links.
 * Sourced entirely from Directus's own directus_activity/directus_revisions
 * system collections — this endpoint never writes anything, and the actor,
 * timestamp and action on every entry were generated by Directus itself from
 * the real authenticated session that performed the original write.
 */
export default defineEventHandler(async (event): Promise<EvidenceAuditEntry[]> => {
  const id = getRouterParam(event, 'id')
  if (!id || isNaN(Number(id))) throw createError({ statusCode: 400, message: 'Invalid product id' })
  await assertProductExists(event, Number(id))

  const recordsResult = await adminFetch<{ data: EvidenceSourceRecordRef[] }>(
    event,
    `/items/product_source_records?filter[product_id][_eq]=${id}` +
    `&filter[fact_key][_starts_with]=spec_item:&fields=id,fact_key&limit=500`,
  )
  const records = (recordsResult as { data: EvidenceSourceRecordRef[] }).data ?? []
  if (records.length === 0) return []

  const idList = records.map(r => r.id).join(',')
  const revisionsResult = await adminFetch<{ data: EvidenceRevision[] }>(
    event,
    `/revisions?filter[collection][_eq]=product_source_records&filter[item][_in]=${idList}` +
    `&fields=id,item,data,activity.action,activity.timestamp,activity.user.email,activity.user.first_name,activity.user.last_name` +
    `&sort=id&limit=500`,
  )
  const revisions = (revisionsResult as { data: EvidenceRevision[] }).data ?? []

  return computeEvidenceAuditEntries(records, revisions)
})
